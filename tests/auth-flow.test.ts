    assert.equal(returning.headers.get('location'), 'https://example.test/workspace');
    assert.ok(returning.headers.get('set-cookie')?.includes('money_token='));
    const owner = await prisma.user.create({ data: { email: 'owner@test.invalid', name: 'Owner', password: 'unused', role: 'OWNER' } });
